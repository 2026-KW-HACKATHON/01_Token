const norm = (s: string) => s.replace(/\s/g, '').toLowerCase();

export function isChain(name: string, categoryPath: string): boolean {
  const n = norm(name);
  if (BRANDS.some((b) => n.includes(norm(b)))) return true;
  const parts = categoryPath.split(' > ');
  const last = parts[parts.length - 1] ?? '';
  return (
    parts.length >= 3 && last.length >= 2 && !GENERIC.has(last) &&
    n.includes(norm(last)) && /점$/.test(name.trim())
  );
}
